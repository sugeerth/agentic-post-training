"""Rollouts: batched, multi-turn tool use with an MLX model (used by the Actor agent).

Each attempt alternates model text and tool results until the model writes <answer>..</answer>, stops, or runs out
of turns. We keep the exact sampled token ids and a mask (1 = generated by the model, 0 = prompt or tool output), so
the learner trains only on the agent's own decisions, never on text the environment wrote.
"""
from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field

from mlx_lm.generate import BatchGenerator
from mlx_lm.sample_utils import make_sampler

from selflearn.usecase import Task


@dataclass
class Trajectory:
    task: Task
    ids: list[int]
    mask: list[int]
    text: str = ""
    calls: int = 0
    reward: float = 0.0
    adv: float = 0.0
    done: bool = field(default=False, repr=False)


def prompt_ids(tok, task: Task, system_prompt: str, user_prefix: str) -> list[int]:
    msgs = [{"role": "system", "content": system_prompt}, {"role": "user", "content": user_prefix + task.question}]
    return list(tok.apply_chat_template(msgs, add_generation_prompt=True))


def generate(model, tok, prompts: list[list[int]], temp: float, max_new: int, stops: tuple[str, ...]):
    """Sample a continuation for each prompt; stop a sequence as soon as its text contains one of `stops`.
    Returns [(token ids, text, ended)] where ended = the model hit EOS or the length limit."""
    gen = BatchGenerator(model, stop_tokens=set(tok.eos_token_ids), sampler=make_sampler(temp=temp),
                         completion_batch_size=len(prompts), prefill_batch_size=min(8, len(prompts)))
    uids = gen.insert(prompts, max_new)
    out = {u: [] for u in uids}
    ended = {u: False for u in uids}
    closed: set = set()
    while responses := gen.next():
        for r in responses:
            if r.uid in closed:
                continue
            if r.finish_reason == "stop":
                ended[r.uid] = True
                closed.add(r.uid)
                continue
            out[r.uid].append(r.token)
            if r.finish_reason is not None:
                ended[r.uid] = True
                closed.add(r.uid)
            elif any(s in tok.decode(out[r.uid][-8:]) for s in stops):
                closed.add(r.uid)
                gen.remove([r.uid])
    gen.close()
    return [(out[u], tok.decode(out[u]), ended[u]) for u in uids]


def rollout(model, tok, tasks: list[Task], *, group: int, temp: float, system_prompt: str,
            tools: dict[str, Callable[[str], str]], call_tool: Callable, user_prefix: str = "Question: ",
            max_turns: int = 4, max_new: int = 96, batch: int = 64) -> list[Trajectory]:
    """`group` attempts per task, in task order (attempts of one task are contiguous). Scoring is the Verifier's job."""
    stops = (*(f"</{name}>" for name in tools), "</answer>")
    trajs = []
    for t in tasks:
        p = prompt_ids(tok, t, system_prompt, user_prefix)
        trajs += [Trajectory(t, list(p), [0] * len(p)) for _ in range(group)]
    for turn in range(max_turns):
        active = [tr for tr in trajs if not tr.done]
        for i in range(0, len(active), batch):
            chunk = active[i:i + batch]
            for tr, (toks, txt, ended) in zip(chunk, generate(model, tok, [tr.ids for tr in chunk], temp, max_new, stops), strict=True):
                tr.ids += toks
                tr.mask += [1] * len(toks)
                tr.text += txt
                result = None if ("</answer>" in txt or ended) else call_tool(txt, tools)
                if result is None:
                    tr.done = True
                    continue
                seg = f"\n<result>{result}</result>\n"
                sid = tok.encode(seg, add_special_tokens=False)
                tr.ids += sid
                tr.mask += [0] * len(sid)
                tr.text += seg
                tr.calls += 1
                tr.done = turn == max_turns - 1
    return trajs
