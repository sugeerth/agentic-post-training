"""Publish a run to the GitHub Pages demo: writes docs/selflearn-<usecase>.js and copies its chart to docs/.

  python3 -m selflearn.publish runs/<run>

The demo page (docs/demo.html, tab "Self-Learning") renders every published use case and shows a switch when there
is more than one, so a new run or a new use case updates the demo without touching the page.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from selflearn.usecases import USE_CASES


def build(run: Path, docs: Path = Path("docs")) -> Path:
    res = json.loads((run / "results.json").read_text())
    uc = USE_CASES[res.get("usecase", "math")]
    before = json.loads((run / "eval_before.json").read_text())["records"]
    after = json.loads((run / "eval_after.json").read_text())["records"]
    msgs = [json.loads(line) for line in (run / "messages.jsonl").read_text().splitlines() if line.strip()]
    t0 = msgs[0]["ts"]
    data = {
        "usecase": uc.name, "summary": uc.summary, "level_note": uc.level_note, "user_prefix": uc.user_prefix,
        "model": res["model"].split("/")[-1], "steps": res["steps"], "selected_step": res.get("selected_step"),
        "kl": res.get("kl", 0.0), "held_out": res["held_out"],
        "minutes": round((msgs[-1]["ts"] - t0) / 60), "fixed": res["fixed"], "broken": res["broken"],
        "before": res["before"], "after": res["after"], "chart": f"selflearn-{uc.name}-report.png",
        "problems": [{"level": b["level"], "question": b["question"], "answer": b["answer"],
                      "base": b["text"].strip(), "base_ok": b["reward"] >= 1.0, "base_calls": b["calls"],
                      "trained": a["text"].strip(), "trained_ok": a["reward"] >= 1.0, "trained_calls": a["calls"]}
                     for b, a in zip(before, after, strict=True)],
        "messages": [{"t": round(m["ts"] - t0, 1), "from": m["sender"], "to": m["receiver"], "text": m["text"]} for m in msgs],
    }
    out = docs / f"selflearn-{uc.name}.js"
    out.write_text(f"// Generated by `python3 -m selflearn.publish {run}`. Real run data; do not edit.\n"
                   "window.SELFLEARN_RUNS = window.SELFLEARN_RUNS || {};\n"
                   f"window.SELFLEARN_RUNS[{json.dumps(uc.name)}] = " + json.dumps(data, separators=(",", ":")) + ";\n")
    shutil.copyfile(run / "report.png", docs / data["chart"])
    return out


if __name__ == "__main__":
    print(build(Path(sys.argv[1])))
