"""Publish a run to the GitHub Pages demo: writes docs/selflearn-data.js and copies the chart to docs/.

  python3 -m selflearn.publish runs/<run>

The demo page (docs/demo.html, tab "Self-Learning") only reads window.SELFLEARN, so a new run updates the demo
without touching the page.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path


def build(run: Path, docs: Path = Path("docs")) -> Path:
    res = json.loads((run / "results.json").read_text())
    before = json.loads((run / "eval_before.json").read_text())["records"]
    after = json.loads((run / "eval_after.json").read_text())["records"]
    msgs = [json.loads(line) for line in (run / "messages.jsonl").read_text().splitlines() if line.strip()]
    steps = [json.loads(line) for line in (run / "steps.jsonl").read_text().splitlines() if line.strip()]
    t0 = msgs[0]["ts"]
    data = {
        "model": res["model"].split("/")[-1], "steps": res["steps"], "held_out": res["held_out"],
        "minutes": round((msgs[-1]["ts"] - t0) / 60), "fixed": res["fixed"], "broken": res["broken"],
        "before": res["before"], "after": res["after"],
        "problems": [{"level": b["level"], "question": b["question"], "answer": b["answer"],
                      "base": b["text"].strip(), "base_ok": b["reward"] == 1.0, "base_calls": b["calls"],
                      "trained": a["text"].strip(), "trained_ok": a["reward"] == 1.0, "trained_calls": a["calls"]}
                     for b, a in zip(before, after, strict=True)],
        "messages": [{"t": round(m["ts"] - t0, 1), "from": m["sender"], "to": m["receiver"], "text": m["text"]} for m in msgs],
        "reward": [round(s["reward"], 3) for s in steps],
    }
    out = docs / "selflearn-data.js"
    out.write_text("// Generated by `python3 -m selflearn.publish " + str(run) + "`. Real run data; do not edit.\n"
                   "window.SELFLEARN = " + json.dumps(data, separators=(",", ":")) + ";\n")
    shutil.copyfile(run / "report.png", docs / "selflearn-report.png")
    return out


if __name__ == "__main__":
    print(build(Path(sys.argv[1])))
